  function translateString(value) {
    if (language !== "en" || value == null) return value;
    const source = normalize(value);
    if (!source) return value;
    if (translations.has(source)) return translations.get(source);
    for (const [pattern, replacement] of patterns) {
      if (pattern.test(source)) return source.replace(pattern, replacement);
    }
    return value;
  }

  function translateTextNode(node) {
    if (!node || node.nodeType !== Node.TEXT_NODE) return;
    const parent = node.parentElement;
    if (!parent || parent.closest("script, style, code, pre, textarea, [data-no-i18n]")) return;
    const translated = translateString(node.nodeValue);
    if (translated === node.nodeValue) return;
    const leading = (node.nodeValue.match(/^\s*/) || [""])[0];
    const trailing = (node.nodeValue.match(/\s*$/) || [""])[0];
    node.nodeValue = leading + translated + trailing;
  }

  function translateElement(root) {
    if (language !== "en" || !root) return;
    if (root.nodeType === Node.TEXT_NODE) {
      translateTextNode(root);
      return;
    }
    if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;

    const elements = root.nodeType === Node.ELEMENT_NODE
      ? [root, ...root.querySelectorAll("*")]
      : [...root.querySelectorAll("*")];
    for (const element of elements) {
      if (element.matches("script, style, code, pre")) continue;
      for (const attribute of ["placeholder", "title", "aria-label", "content", "data-text"]) {
        if (!element.hasAttribute(attribute)) continue;
        const original = element.getAttribute(attribute);
        const translated = translateString(original);
        if (translated !== original) element.setAttribute(attribute, translated);
      }
      for (const child of element.childNodes) {
        if (child.nodeType === Node.TEXT_NODE) translateTextNode(child);
      }
    }
  }

